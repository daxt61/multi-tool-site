export function GraphQLToSeaORM({ initialData, onStateChange }: { initialData?: any; onStateChange?: (state: any) => void }) {
  const { t } = useTranslation();
  const inputRef = useRef<HTMLTextAreaElement>(null);
  const [input, setInput] = useState(initialData?.input || '');
  const [output, setOutput] = useState(initialData?.output || '');
  const [activePreset, setActivePreset] = useState<string | null>(null);
  const [outputMode, setOutputMode] = useState<'full' | 'model_only'>('full');
  const [casing, setCasing] = useState<'snake_case' | 'camelCase' | 'PascalCase' | 'original'>(
    initialData?.casing || 'snake_case'
  );
  const [deriveSerde, setDeriveSerde] = useState(initialData?.deriveSerde ?? true);
  const [deriveEq, setDeriveEq] = useState(initialData?.deriveEq ?? true);
  const [primaryKeyAutoIncrement, setPrimaryKeyAutoIncrement] = useState(initialData?.primaryKeyAutoIncrement ?? true);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    onStateChange?.({
      input,
      output,
      outputMode,
      casing,
      deriveSerde,
      deriveEq,
      primaryKeyAutoIncrement
    });
  }, [input, output, outputMode, casing, deriveSerde, deriveEq, primaryKeyAutoIncrement, onStateChange]);

  const toPascalCase = (str: string) => {
    return str
      .replace(/[^a-zA-Z0-9]/g, ' ')
      .split(' ')
      .filter(Boolean)
      .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
      .join('') || 'AutoGeneratedEntity';
  };

  const toSnakeCase = (str: string) => {
    let result = str
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .replace(/[^a-zA-Z0-9]/g, '_')
      .replace(/_+/g, '_')
      .toLowerCase();

    if (/^[0-9]/.test(result)) {
      result = 'f_' + result;
    }
    return result;
  };

  const toCamelCase = (str: string) => {
    const pascal = toPascalCase(str);
    return pascal.charAt(0).toLowerCase() + pascal.slice(1);
  };

  const formatFieldName = (fieldName: string): { rustKey: string; originalName: string } => {
    let formattedKey = fieldName;
    if (casing === 'snake_case') {
      formattedKey = toSnakeCase(fieldName);
    } else if (casing === 'camelCase') {
      formattedKey = toCamelCase(fieldName);
    } else if (casing === 'PascalCase') {
      formattedKey = toPascalCase(fieldName);
    }

    let rustKey = formattedKey;
    if (/^[0-9]/.test(rustKey)) {
      rustKey = 'f_' + rustKey;
    }

    if (RUST_KEYWORDS.has(rustKey)) {
      rustKey = 'r#' + rustKey;
    }

    return { rustKey, originalName: fieldName };
  };

  const mapGqlTypeToSeaORM = (gqlTypeStr: string, knownEnums: Set<string>): { rustType: string; columnType?: string; isOptional: boolean } => {
    const raw = gqlTypeStr.trim();
    const isNonNull = raw.endsWith('!');
    const baseType = isNonNull ? raw.slice(0, -1).trim() : raw;
    const isOptional = !isNonNull;

    if (baseType === 'String') return { rustType: 'String', isOptional };
    if (baseType === 'Int') return { rustType: 'i32', isOptional };
    if (baseType === 'Float') return { rustType: 'f64', isOptional };
    if (baseType === 'Boolean') return { rustType: 'bool', isOptional };
    if (baseType === 'ID') return { rustType: 'i32', isOptional };
    if (baseType === 'DateTime' || baseType === 'Date' || baseType === 'Timestamp') {
      return { rustType: 'DateTime', isOptional };
    }
    if (baseType === 'JSON' || baseType === 'JSONObject') {
      return { rustType: 'Json', columnType: 'Json', isOptional };
    }

    if (knownEnums.has(baseType)) {
      return { rustType: baseType, isOptional };
    }

    if (baseType.startsWith('[') && baseType.endsWith(']')) {
      return { rustType: 'Json', columnType: 'Json', isOptional };
    }

    return { rustType: 'String', isOptional };
  };

  const handleConvert = useCallback(() => {
    try {
      if (!input.trim()) {
        setOutput('');
        setError('');
        return;
      }
      if (input.length > MAX_LENGTH) {
        setError(t('error.max_length', { max: MAX_LENGTH.toLocaleString() }));
        return;
      }

      // Strip GraphQL comments
      const cleanInput = input
        .replace(/#.*$/gm, '')
        .replace(/"""[\s\S]*?"""/g, '')
        .replace(/"[\s\S]*?"/g, (m: string) => m.includes('\n') ? '""' : m);

      // Collect known Enums
      const knownEnums = new Set<string>();
      const enumCollectRegex = /enum\s+([A-Za-z0-9_]+)\s*\{([^}]*)\}/g;
      let enumMatch;
      while ((enumMatch = enumCollectRegex.exec(cleanInput)) !== null) {
        if (enumMatch[1]) knownEnums.add(enumMatch[1]);
      }

      const enumBlocks: string[] = [];
      const entityBlocks: string[] = [];

      // 1. Process Enums into SeaORM EnumIter / DeriveActiveEnum if needed
      const enumRegex = /enum\s+([A-Za-z0-9_]+)\s*\{([^}]*)\}/g;
      let eMatch;
      while ((eMatch = enumRegex.exec(cleanInput)) !== null) {
        const enumName = eMatch[1];
        const enumValues = eMatch[2]
          .split(/\s+/)
          .map(v => v.trim())
          .filter(Boolean);

        if (enumValues.length > 0) {
          let enumCode = `#[derive(Debug, Clone, PartialEq, Eq, EnumIter, DeriveActiveEnum)]\n`;
          enumCode += `#[sea_orm(rs_type = "String", db_type = "Enum", enum_name = "${toSnakeCase(enumName)}")]\n`;
          enumCode += `pub enum ${enumName} {\n`;
          enumValues.forEach(val => {
            const variantName = toPascalCase(val);
            enumCode += `    #[sea_orm(string_value = "${val}")]\n`;
            enumCode += `    ${variantName},\n`;
          });
          enumCode += `}\n`;
          enumBlocks.push(enumCode);
        }
      }

      // 2. Process Structs / Object Types / Inputs
      const structRegex = /(type|interface|input)\s+([A-Za-z0-9_]+)(?:\s+implements\s+[^{]+)?\s*\{([^}]*)\}/g;
      let sMatch;

      const derives = ['Clone', 'Debug', 'PartialEq', 'DeriveEntityModel'];
      if (deriveEq) derives.push('Eq');
      if (deriveSerde) derives.push('Serialize', 'Deserialize');

      while ((sMatch = structRegex.exec(cleanInput)) !== null) {
        const kind = sMatch[1];
        const typeName = sMatch[2];
        const body = sMatch[3];

        if (kind === 'interface') continue; // SeaORM models map to concrete types or inputs

        const tableName = toSnakeCase(typeName);
        const moduleName = tableName;

        const normalizedBody = body
          .replace(/(!|[a-zA-Z0-9_\]]+)\s+([a-zA-Z0-9_$]+)\s*:/g, '$1\n$2:')
          .trim();

        const lines = normalizedBody
          .split('\n')
          .map(l => l.trim())
          .filter(l => l && !l.startsWith('#'));

        const fields: Array<{
          rustKey: string;
          originalName: string;
          rustType: string;
          columnType?: string;
          isPrimaryKey: boolean;
          isOptional: boolean;
        }> = [];

        lines.forEach(line => {
          const cleanLine = line.replace(/\([^)]*\)/, '');
          const colonIdx = cleanLine.indexOf(':');
          if (colonIdx === -1) return;

          const rawFieldName = cleanLine.substring(0, colonIdx).trim();
          const rawTypeStr = cleanLine.substring(colonIdx + 1).trim();

          if (!rawFieldName || !rawTypeStr) return;

          const isPrimaryKey = rawFieldName === 'id' || rawFieldName.endsWith('Id') && fields.length === 0;
          const { rustType, columnType, isOptional } = mapGqlTypeToSeaORM(rawTypeStr, knownEnums);
          const { rustKey, originalName } = formatFieldName(rawFieldName);

          fields.push({
            rustKey,
            originalName,
            rustType,
            columnType,
            isPrimaryKey,
            isOptional
          });
        });

        if (fields.length === 0) continue;

        let block = '';
        const indent = (outputMode === 'full') ? '    ' : '';

        if (outputMode === 'full') {
          block += `pub mod ${moduleName} {\n    use super::*;\n\n`;
        }

        block += `${indent}#[derive(${derives.join(', ')})]\n`;
        block += `${indent}#[sea_orm(table_name = "${tableName}")]\n`;
        block += `${indent}pub struct Model {\n`;

        fields.forEach(field => {
          const attributes: string[] = [];
          if (field.isPrimaryKey) {
            if (!primaryKeyAutoIncrement) {
              attributes.push('primary_key', 'auto_increment = false');
            } else {
              attributes.push('primary_key');
            }
          }
          if (field.columnType) {
            attributes.push(`column_type = "${field.columnType}"`);
          }
          if (field.rustKey !== field.originalName) {
            attributes.push(`column_name = "${field.originalName}"`);
          }

          if (attributes.length > 0) {
            block += `${indent}    #[sea_orm(${attributes.join(', ')})]\n`;
          }

          const fieldTypeStr = field.isOptional ? `Option<${field.rustType}>` : field.rustType;
          block += `${indent}    pub ${field.rustKey}: ${fieldTypeStr},\n`;
        });

        block += `${indent}}\n\n`;

        // Relation Enum
        block += `${indent}#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]\n`;
        block += `${indent}pub enum Relation {}\n\n`;
        block += `${indent}impl ActiveModelBehavior for ActiveModel {}\n`;

        if (outputMode === 'full') {
          block += `}\n`;
        }

        entityBlocks.push(block);
      }

      if (enumBlocks.length === 0 && entityBlocks.length === 0) {
        setError(t('graphqltoseaorm.no_types_found', 'No valid GraphQL types, inputs, or enums found.'));
        setOutput('');
        return;
      }

      let generatedCode = 'use sea_orm::entity::prelude::*;\n';
      if (deriveSerde) {
        generatedCode += 'use serde::{Serialize, Deserialize};\n';
      }
      generatedCode += '\n';

      if (enumBlocks.length > 0) {
        generatedCode += enumBlocks.join('\n') + '\n';
      }

      if (entityBlocks.length > 0) {
        generatedCode += entityBlocks.join('\n\n');
      }

      setOutput(generatedCode.trim());
      setError('');
    } catch (e: any) {
      setError(t('graphqltoseaorm.error_parsing', 'Error parsing GraphQL schema') + ': ' + e.message);
      setOutput('');
    }
  }, [input, outputMode, casing, deriveSerde, deriveEq, primaryKeyAutoIncrement, t]);

  useEffect(() => {
    handleConvert();
  }, [handleConvert]);

  const handleCopy = useCallback(() => {
    if (!output) return;
    navigator.clipboard.writeText(output);
    setCopied(true);
    toast.success(t('common.copied', 'Copied to clipboard!'));
    setTimeout(() => setCopied(false), 2000);
  }, [output, t]);

  const handleClear = useCallback(() => {
    setInput('');
    setOutput('');
    setError('');
    setActivePreset(null);
    toast.success(t('common.cleared', 'Cleared!'));
    setTimeout(() => inputRef.current?.focus(), 0);
  }, [t]);

  const handleDownload = () => {
    if (!output) return;
    const blob = new Blob([output], { type: 'text/x-rust' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'entity.rs';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    toast.success(t('common.downloaded', 'Downloaded entity.rs!'));
  };

  const loadPreset = (presetKey: keyof typeof PRESETS) => {
    setInput(PRESETS[presetKey]);
    setActivePreset(presetKey);
    toast.success(t('graphqltoseaorm.preset_loaded', 'Loaded SeaORM GraphQL preset!'));
  };

  const handlersRef = useRef({ handleClear, handleCopy, output });
  useEffect(() => {
    handlersRef.current = { handleClear, handleCopy, output };
  }, [handleClear, handleCopy, output]);

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      const activeElement = document.activeElement;
      const isEditable =
        activeElement instanceof HTMLInputElement ||
        activeElement instanceof HTMLTextAreaElement ||
        activeElement instanceof HTMLSelectElement ||
        activeElement?.getAttribute("contenteditable") === "true";

      if (isEditable && e.key !== 'Escape') return;

      if (e.metaKey || e.ctrlKey || e.altKey || e.shiftKey) return;

      if (e.key === "Escape") {
        e.preventDefault();
        handlersRef.current.handleClear();
      } else if (e.key.toLowerCase() === "c") {
        if (handlersRef.current.output) {
          e.preventDefault();
          handlersRef.current.handleCopy();
        }
      }
    };

    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, []);

  return (
    <div className="max-w-6xl mx-auto space-y-8 animate-in fade-in duration-500">
      {/* Presets Bar */}
      <div className="flex flex-wrap items-center justify-between gap-4 p-4 bg-slate-50 dark:bg-slate-900/50 rounded-2xl border border-slate-200 dark:border-slate-800">
        <div className="flex items-center gap-2">
          <Sparkles className="w-4 h-4 text-amber-500" aria-hidden="true" />
          <span className="text-xs font-bold uppercase tracking-widest text-slate-500 dark:text-slate-400">
            {t('graphqltoseaorm.presets_title', 'Clickable Presets')}
          </span>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <button
            onClick={() => loadPreset('ecommerce')}
            aria-pressed={activePreset === 'ecommerce'}
            className={`px-3 py-1.5 text-xs font-bold rounded-xl transition-all shadow-sm focus-visible:ring-2 focus-visible:ring-indigo-500 focus-visible:outline-none ${
              activePreset === 'ecommerce'
                ? 'bg-indigo-600 text-white border-indigo-600'
                : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 hover:border-indigo-500'
            }`}
          >
            {t('graphqltoseaorm.preset_ecommerce', 'E-Commerce Catalog')}
          </button>
          <button
            onClick={() => loadPreset('user_auth')}
            aria-pressed={activePreset === 'user_auth'}
            className={`px-3 py-1.5 text-xs font-bold rounded-xl transition-all shadow-sm focus-visible:ring-2 focus-visible:ring-indigo-500 focus-visible:outline-none ${
              activePreset === 'user_auth'
                ? 'bg-indigo-600 text-white border-indigo-600'
                : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 hover:border-indigo-500'
            }`}
          >
            {t('graphqltoseaorm.preset_user_auth', 'User Auth & Roles')}
          </button>
          <button
            onClick={() => loadPreset('social_feed')}
            aria-pressed={activePreset === 'social_feed'}
            className={`px-3 py-1.5 text-xs font-bold rounded-xl transition-all shadow-sm focus-visible:ring-2 focus-visible:ring-indigo-500 focus-visible:outline-none ${
              activePreset === 'social_feed'
                ? 'bg-indigo-600 text-white border-indigo-600'
                : 'bg-white dark:bg-slate-800 border border-slate-200 dark:border-slate-700 hover:border-indigo-500'
            }`}
          >
            {t('graphqltoseaorm.preset_social_feed', 'Social Feed & Comments')}
          </button>
        </div>
      </div>

      {/* Options Panel */}
      <div className="grid grid-cols-1 md:grid-cols-3 lg:grid-cols-4 gap-4 p-5 bg-white dark:bg-slate-900/60 rounded-2xl border border-slate-200 dark:border-slate-800">
        <div className="space-y-1.5">
          <label htmlFor="gql-seaorm-output-mode" className="text-xs font-bold uppercase tracking-widest text-slate-500 dark:text-slate-400">
            {t('graphqltoseaorm.output_mode_label', 'Output Layout')}
          </label>
          <select
            id="gql-seaorm-output-mode"
            value={outputMode}
            onChange={(e) => setOutputMode(e.target.value as any)}
            className="w-full p-2.5 bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl text-sm font-semibold outline-none focus:ring-2 focus:ring-indigo-500"
          >
            <option value="full">Full Entity Modules (pub mod)</option>
            <option value="model_only">Model Struct Only</option>
          </select>
        </div>

        <div className="space-y-1.5">
          <label htmlFor="gql-seaorm-casing" className="text-xs font-bold uppercase tracking-widest text-slate-500 dark:text-slate-400">
            {t('graphqltoseaorm.casing_label', 'Field Casing')}
          </label>
          <select
            id="gql-seaorm-casing"
            value={casing}
            onChange={(e) => setCasing(e.target.value as any)}
            className="w-full p-2.5 bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl text-sm font-semibold outline-none focus:ring-2 focus:ring-indigo-500"
          >
            <option value="snake_case">snake_case (Rust standard)</option>
            <option value="camelCase">camelCase</option>
            <option value="PascalCase">PascalCase</option>
            <option value="original">original (unchanged)</option>
          </select>
        </div>

        <div className="flex flex-col justify-center space-y-2 pt-2">
          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={deriveSerde}
              onChange={(e) => setDeriveSerde(e.target.checked)}
              className="w-4 h-4 text-indigo-600 rounded border-slate-300 focus:ring-indigo-500"
            />
            <span className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Derive Serde (Serialize, Deserialize)
            </span>
          </label>
          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={deriveEq}
              onChange={(e) => setDeriveEq(e.target.checked)}
              className="w-4 h-4 text-indigo-600 rounded border-slate-300 focus:ring-indigo-500"
            />
            <span className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Derive Eq
            </span>
          </label>
        </div>

        <div className="flex flex-col justify-center space-y-2 pt-2">
          <label className="flex items-center gap-2 cursor-pointer">
            <input
              type="checkbox"
              checked={primaryKeyAutoIncrement}
              onChange={(e) => setPrimaryKeyAutoIncrement(e.target.checked)}
              className="w-4 h-4 text-indigo-600 rounded border-slate-300 focus:ring-indigo-500"
            />
            <span className="text-xs font-bold text-slate-700 dark:text-slate-300">
              Auto-increment Primary Keys
            </span>
          </label>
        </div>
      </div>

      {/* Editor Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
        <div className="space-y-4">
          <div className="flex justify-between items-center px-1">
            <div className="flex items-center gap-2">
              <FileCode className="w-4 h-4 text-indigo-500" aria-hidden="true" />
              <label htmlFor="graphql-seaorm-input" className="text-xs font-black uppercase tracking-widest text-slate-400 cursor-pointer">
                {t('graphqltoseaorm.graphql_input_label', 'GraphQL SDL Schema')}
              </label>
            </div>
            <div className="flex items-center gap-2">
              <Kbd modifier={null} className="hidden sm:inline-flex border-rose-200 dark:border-rose-800 text-rose-400 dark:bg-slate-900">Esc</Kbd>
              <button
                onClick={handleClear}
                disabled={!input && !output}
                className="text-xs font-bold px-3 py-1.5 rounded-xl text-rose-500 bg-rose-50 dark:bg-rose-500/10 hover:bg-rose-100 dark:hover:bg-rose-500/20 transition-all flex items-center gap-1 disabled:opacity-50 focus-visible:ring-2 focus-visible:ring-rose-500 focus-visible:outline-none"
              >
                <Trash2 className="w-3 h-3" aria-hidden="true" /> {t('common.clear')}
              </button>
            </div>
          </div>
          <textarea
            id="graphql-seaorm-input"
            ref={inputRef}
            value={input}
            onChange={(e) => {
              setInput(e.target.value);
              setActivePreset(null);
            }}
            placeholder={t('graphqltoseaorm.placeholder_graphql', 'Paste GraphQL SDL schema statements here...')}
            className="w-full h-[450px] p-6 bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-3xl outline-none focus:ring-2 focus:ring-indigo-500/20 transition-all font-mono text-sm leading-relaxed dark:text-slate-300 resize-none"
          />
        </div>

        <div className="space-y-4">
          <div className="flex justify-between items-center px-1">
            <div className="flex items-center gap-2">
              <FileCode className="w-4 h-4 text-emerald-500" aria-hidden="true" />
              <label htmlFor="gql-seaorm-output" className="text-xs font-black uppercase tracking-widest text-slate-400 cursor-pointer">
                {t('graphqltoseaorm.output_label', 'SeaORM Entity Definitions')}
              </label>
            </div>
            <div className="flex gap-2">
              <button
                onClick={handleDownload}
                disabled={!output}
                className="text-xs font-bold px-3 py-1.5 rounded-xl text-indigo-500 bg-indigo-50 dark:bg-indigo-500/10 hover:bg-indigo-100 transition-all flex items-center gap-1 disabled:opacity-50 focus-visible:ring-2 focus-visible:ring-indigo-500 focus-visible:outline-none"
              >
                <Download className="w-3 h-3" aria-hidden="true" /> {t('common.download')}
              </button>
              <button
                onClick={handleCopy}
                disabled={!output}
                className={`text-xs font-bold px-3 py-1.5 rounded-xl transition-all flex items-center gap-1 border focus-visible:ring-2 focus-visible:ring-indigo-500 focus-visible:outline-none ${
                  copied
                    ? 'bg-emerald-50 dark:bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border border-emerald-200 dark:border-emerald-500/20'
                    : 'text-slate-500 bg-slate-100 dark:bg-slate-800 border-transparent hover:bg-slate-200 dark:hover:bg-slate-700 disabled:opacity-50 disabled:cursor-not-allowed'
                }`}
              >
                {copied ? <Check className="w-3 h-3" aria-hidden="true" /> : <Copy className="w-3 h-3" aria-hidden="true" />} {copied ? t('common.copied') : t('common.copy')}
                {!copied && input && <Kbd modifier={null} className="hidden sm:inline-flex w-4 h-4 bg-white/50 dark:bg-black/20 ml-1">C</Kbd>}
              </button>
            </div>
          </div>
          <textarea
            id="gql-seaorm-output"
            value={output}
            readOnly
            placeholder={t('graphqltoseaorm.placeholder_output', 'Rust SeaORM entity definitions will appear here...')}
            className="w-full h-[450px] p-6 bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-3xl outline-none font-mono text-sm leading-relaxed text-indigo-600 dark:text-indigo-400 resize-none"
          />
        </div>
      </div>

      {error && (
        <div className="bg-rose-50 dark:bg-rose-500/10 border border-rose-200 dark:border-rose-800 p-4 rounded-2xl flex items-center gap-3 text-rose-600 dark:text-rose-400 font-bold animate-in fade-in slide-in-from-top-2">
          <AlertCircle className="w-5 h-5" aria-hidden="true" />
          {error}
        </div>
      )}

      <div className="bg-indigo-50 dark:bg-indigo-900/10 p-8 rounded-[2.5rem] border border-indigo-100 dark:border-indigo-900/20 flex items-start gap-4">
        <Info className="w-6 h-6 text-indigo-500 mt-1" aria-hidden="true" />
        <div className="space-y-2">
          <h4 className="font-bold dark:text-white">{t('graphqltoseaorm.about_title', 'About GraphQL SDL to SeaORM Entity Generator')}</h4>
          <p className="text-sm text-slate-500 dark:text-slate-400 leading-relaxed">
            {t('graphqltoseaorm.about_text', 'Convert GraphQL Schema Definition Language (SDL) definitions directly into Rust SeaORM Entity models. Generates DeriveEntityModel attributes, DeriveActiveEnum representations for GraphQL enums, primary key options, and data type mappings.')}
          </p>
        </div>
      </div>
    </div>
  );
}
